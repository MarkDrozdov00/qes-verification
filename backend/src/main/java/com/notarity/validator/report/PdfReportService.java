        static String padesLevel(String value) { return value == null ? null : value.replace("B_", "B-").replace('_', '-'); }
        static List<String> wrap(String value, PDFont font, float size, float maxWidth) throws IOException {
            if (value == null || value.isBlank()) return List.of();
            List<String> lines = new ArrayList<>();
            for (String paragraph : value.split("\\R", -1)) {
                StringBuilder line = new StringBuilder();
                for (String word : paragraph.split("\\s+")) {
                    if (word.isEmpty()) continue;
                    String candidate = line.isEmpty() ? word : line + " " + word;
                    if (width(candidate, font, size) <= maxWidth) line = new StringBuilder(candidate);
                    else if (line.isEmpty()) splitLongWord(word, font, size, maxWidth, lines);
                    else { lines.add(line.toString()); line = new StringBuilder(word); if (width(word, font, size) > maxWidth) { line.setLength(0); splitLongWord(word, font, size, maxWidth, lines); } }
                }
                if (!line.isEmpty()) lines.add(line.toString());
            }
            return lines;
        }
        static void splitLongWord(String word, PDFont font, float size, float maxWidth, List<String> lines) throws IOException { StringBuilder part = new StringBuilder(); for (int offset = 0; offset < word.length();) { int point = word.codePointAt(offset); String next = part + new String(Character.toChars(point)); if (!part.isEmpty() && width(next, font, size) > maxWidth) { lines.add(part.toString()); part.setLength(0); } part.appendCodePoint(point); offset += Character.charCount(point); } if (!part.isEmpty()) lines.add(part.toString()); }
        static void roundedRect(PDPageContentStream stream, float x, float y, float width, float height, float radius) throws IOException { float k = .55228475f, c = radius * k; stream.moveTo(x + radius, y); stream.lineTo(x + width - radius, y); stream.curveTo(x + width - radius + c, y, x + width, y + radius - c, x + width, y + radius); stream.lineTo(x + width, y + height - radius); stream.curveTo(x + width, y + height - radius + c, x + width - radius + c, y + height, x + width - radius, y + height); stream.lineTo(x + radius, y + height); stream.curveTo(x + radius - c, y + height, x, y + height - radius + c, x, y + height - radius); stream.lineTo(x, y + radius); stream.curveTo(x, y + radius - c, x + radius - c, y, x + radius, y); stream.closePath(); }
