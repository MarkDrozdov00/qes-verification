    public byte[] generate(ReportTemplateModel model) {
        try (PDDocument document = new PDDocument(); ByteArrayOutputStream output = new ByteArrayOutputStream()) {
            Fonts fonts = Fonts.load(document);
            Canvas canvas = new Canvas(document, fonts, notaryRegistry);
            render(canvas, model);
            canvas.close();
            addFooters(document, model, fonts);
            document.save(output);
            return output.toByteArray();
        } catch (IOException exception) {
            throw new ReportGenerationException(exception);
        }
    }

    private void render(Canvas c, ReportTemplateModel model) throws IOException {
        DocumentValidationResponse r = model.validation();
        c.reportHeader();
        c.resultHero(r);
        c.compactSectionTitle("Document information", 92);
        c.documentGrid(r.document());
        c.compactSectionTitle("Trust summary", 158);
        c.trustGrid(ReportPresentation.trustSummary(r));

        c.compactSectionTitle("Embedded signatures", r.signatures().isEmpty() ? 38 : 132);
        if (r.signatures().isEmpty()) c.callout("No supported embedded signatures were found.", PALE, MUTED);
        else c.compactSignature(r.signatures().getFirst());

        if (r.signatures().size() > 1) {
            c.newPage();
            c.continuationHeader("Embedded signatures");
            for (int index = 1; index < r.signatures().size(); index++) c.compactSignature(r.signatures().get(index));
        }
        c.registryGrid(r.notarityCheck(), r.notaryCheck());
        c.reportDisclaimers();
    }

    private static void addFooters(PDDocument document, ReportTemplateModel model, Fonts fonts) throws IOException {
        int total = document.getNumberOfPages();
        for (int i = 0; i < total; i++) {
            try (PDPageContentStream stream = new PDPageContentStream(document, document.getPage(i), PDPageContentStream.AppendMode.APPEND, true)) {
                stream.setStrokingColor(LINE); stream.moveTo(Canvas.LEFT, 43); stream.lineTo(Canvas.RIGHT, 43); stream.stroke();
                String left = "Generated by Signature Validator Prototype | Validator " + model.validation().validatorVersion();
                String right = "Generated " + format(model.generatedAt()) + " | Page " + (i + 1) + " of " + total;
                write(stream, left, fonts.regular(), 7.5f, MUTED, Canvas.LEFT, 27);
                write(stream, right, fonts.regular(), 7.5f, MUTED, Canvas.RIGHT - width(right, fonts.regular(), 7.5f), 27);
            }
        }
    }

    private record Fonts(PDFont regular, PDFont bold, PDFont mono) {
        static Fonts load(PDDocument document) throws IOException {
            return new Fonts(load(document, "/fonts/DejaVuSans.ttf"), load(document, "/fonts/DejaVuSans-Bold.ttf"),
                load(document, "/fonts/DejaVuSansMono.ttf"));
        }
        private static PDFont load(PDDocument document, String resource) throws IOException {
            try (InputStream stream = PdfReportService.class.getResourceAsStream(resource)) {
                if (stream == null) throw new IOException("Embedded report font is unavailable: " + resource);
                return PDType0Font.load(document, stream, true);
            }
        }
    }

    private record Row(String label, String value, boolean mono) {}
    private static Row row(String label, Object value) { return new Row(label, text(value), false); }
    private static Row mono(String label, Object value) { return new Row(label, text(value), true); }
    private static String text(Object value) { return value == null || value.toString().isBlank() ? null : value.toString(); }
    private static String statusLabel(Enum<?> value) { return value == null ? "Not available" : title(value.name()); }
    private static String title(String value) { String lower = value.replace('_', ' ').toLowerCase(Locale.ROOT); return Character.toUpperCase(lower.charAt(0)) + lower.substring(1); }
    private static String format(Instant value) { return value == null ? null : DATE.format(value); }
    private static String formatDay(Instant value) { return value == null ? null : DAY.format(value); }
    private static String formatBytes(long bytes) { return bytes < 1024 * 1024 ? String.format(Locale.ROOT, "%.1f KB", bytes / 1024d) : String.format(Locale.ROOT, "%.1f MB", bytes / 1048576d); }
    private static String formatDuration(long millis) { return millis >= 1000 ? String.format(Locale.ROOT, "%.1f seconds", millis / 1000d) : millis + " ms"; }
    private static Color tone(OverallValidationStatus status) { return status == OverallValidationStatus.INVALID ? ERROR : status == OverallValidationStatus.INDETERMINATE || status == OverallValidationStatus.VERIFIED_WITH_WARNINGS ? WARNING : status == OverallValidationStatus.UNSIGNED ? MUTED : SUCCESS; }
    private static Color tone(CheckStatus status) { return status == CheckStatus.INVALID ? ERROR : status == CheckStatus.WARNING || status == CheckStatus.INDETERMINATE ? WARNING : status == CheckStatus.VALID ? SUCCESS : MUTED; }
    private static float width(String text, PDFont font, float size) throws IOException { return font.getStringWidth(text == null ? "" : text) / 1000f * size; }
    private static void write(PDPageContentStream stream, String text, PDFont font, float size, Color color, float x, float y) throws IOException { stream.beginText(); stream.setFont(font, size); stream.setNonStrokingColor(color); stream.newLineAtOffset(x, y); stream.showText(text == null ? "" : text); stream.endText(); }

